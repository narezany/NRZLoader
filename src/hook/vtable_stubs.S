// Подставки, которые считают вызовы виртуальных методов и пропускают их дальше.
//
// Имён методов у нас нет — Mojang вырезала их и из клиента, и из сервера.
// Зато можно узнать, что делает метод, по тому, когда он вызывается: тот, что
// срабатывает двадцать раз в секунду, — это тик, а тот, что раз при ударе, —
// обработка урона. Для этого в таблицу вместо настоящего адреса кладётся
// подставка: она увеличивает счётчик и прыгает на настоящий метод.
//
// Написано на ассемблере не из любви к нему, а по необходимости: подставка
// стоит между вызывающим и методом, и все аргументы должны дойти нетронутыми.
// На C++ такого не выразить, не зная, сколько у метода аргументов и какие они.
// Здесь же не трогается ничего, кроме x16 и x17, — а эти два регистра по
// соглашению и так считаются испорченными при переходе.

#if defined(__aarch64__)

    .text
    .align  4

    // Счётчик и настоящий адрес лежат парой, одно за другим. Так одной
    // вычисленной базы хватает и на то, и на другое, и подставка умещается в
    // семь команд вместо девяти.
    //
    // Номер подставки берётся из nrz_index — обычного числа, которое
    // переопределяется перед каждым разворотом. Через параметр макроса было
    // бы понятнее, но ассемблер тогда отказывается считать смещение.
    .macro  NRZ_STUB
    adrp    x16, nrz_probe_slots
    add     x16, x16, :lo12:nrz_probe_slots
    ldr     x17, [x16, #(16 * nrz_index)]
    add     x17, x17, #1
    str     x17, [x16, #(16 * nrz_index)]
    ldr     x16, [x16, #(16 * nrz_index + 8)]
    br      x16
    nop
    .endm

    .global nrz_probe_stubs
    .hidden nrz_probe_stubs
nrz_probe_stubs:
    .set    nrz_index, 0
    .rept   256
    NRZ_STUB
    .set    nrz_index, nrz_index + 1
    .endr

#endif  // __aarch64__

    // Стек здесь не исполняется; без этого линкер ругается на весь модуль.
    .section .note.GNU-stack, "", %progbits
