// Узнаёт, что делает виртуальный метод, по тому, когда его зовут.
//
// Адреса таблиц у нас есть — их находит лаунчер. Имён методов нет нигде: их
// вырезали и из клиента, и из сервера, так что взять их неоткуда. Но метод
// выдаёт себя поведением. Тот, что срабатывает двадцать раз в секунду, — тик.
// Тот, что один раз, когда игрок получил урон, — обработка урона. Тот, что
// молчит всё время, — что-то редкое.
//
// Поэтому в таблицу вместо настоящих адресов кладутся подставки со
// счётчиками, а рядом пишется отчёт: какой номер сколько раз сработал. Дальше
// человек играет полминуты и читает по нему, что есть что — на своей версии
// игры, без чужих таблиц соответствия, которые устаревают с каждым
// обновлением.
#pragma once

#include <string>

namespace mcbe {

class Loader;

namespace probe {

// Ставит счётчики на таблицу класса, названного в настройках, и заводит поток,
// который сохраняет отчёт. Ничего не делает, пока `probe.class` не задан:
// подмена таблицы — вещь заметная, и включаться сама она не должна.
bool install(Loader& loader, const std::string& config_path);

// Сохраняет отчёт прямо сейчас.
void write_report();

}  // namespace probe
}  // namespace mcbe
