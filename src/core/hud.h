// Окошко поверх игры с тем, что загрузчик про неё знает.
//
// Знает он это не из полей игрока — где они лежат, неизвестно, — а по тому,
// какие методы сейчас вызываются. Прыжок виден потому, что срабатывает метод,
// который срабатывает только при прыжке. Так же и плавание, и добыча блока.
//
// Отсюда и то, чего здесь нет. Координаты и угол камеры — это числа внутри
// объекта игрока, а не вызовы; по вызовам их не увидеть, и выдумывать их
// вместо честного прочерка было бы враньём в самом заметном месте.
#pragma once

#include <cstddef>
#include <cstdint>
#include <string>

namespace mcbe {

class Loader;

namespace hud {

// Открывает окошко и начинает его обновлять. Номера слотов берутся из
// настроек, потому что у каждой сборки игры они свои.
bool install(Loader& loader, const std::string& config_path);

// Обновляет содержимое; вызывается несколько раз в секунду.
void refresh();

// Работает ли окошко.
bool running();

}  // namespace hud
}  // namespace mcbe
